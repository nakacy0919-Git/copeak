assert(intro.includes('診断スタート！'),'Primary CTA');
assert(intro.indexOf('id="vcQuick"')<intro.indexOf('id="vcDeep"'),'Quick first');
assert.equal((intro.match(/data-level="[1-8]"/g)||[]).length,8);
assert(!intro.includes('暫定・学習用'),'Remove extra label');
assert(!intro.includes('vcFocusStats'),'Remove developer statistics');
assert(intro.includes('<details class="vc-history-details">'),'History collapsed');
assert(intro.includes('<details class="vc-about-details">'),'Required caveat accessible');
for(const id of ['vcQuick','vcDeep','vcDashboardLevel','vcDashboardDelta','vcTrendGraph','vcLoadState'])assert(intro.includes('id="'+id+'"'),id+' missing');
assert(js.includes("const KEY = 'copeak_chunk_diagnosis_v1'"));
assert(js.includes('nextTarget(session.answers,session.estimate)'));
assert(js.includes("$('vcQuick').disabled=false")&&js.includes("$('vcDeep').disabled=false"));
