import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('vocabulary-check.html');
const css=read('vocabulary-ipad.css');
const originalCss=read('vocabulary-check.css');
const js=read('vocabulary-check.js');
assert(html.includes('vocabulary-check.css?v=8.7.4'));
assert(html.includes('vocabulary-check.js?v=8.7.4'));
assert(html.includes('vocabulary-review.js?v=8.7.0'));
assert(html.includes('vocabulary-quality.js?v=8.7.0'));
const premium=html.indexOf('copeak-premium.css?v=20261103');
const tablet=html.indexOf('vocabulary-ipad.css?v=8.7.5');
assert(premium>=0 && tablet>premium,'tablet overrides load after premium');
assert(css.includes('iPad vocabulary check'));
assert(css.includes('@media (min-width:701px) and (max-width:1400px)'));
assert(css.includes('(orientation:portrait)'));
assert(css.includes('(orientation:landscape)'));
assert(css.includes('max-height:700px'));
assert(/body\.vc-is-quiz \.vc-question-card\s*\{[^}]*overflow-y:auto/s.test(css));
assert(/body\.vc-is-result \.vc-summary-panel\s*\{[^}]*overflow-y:auto/s.test(css));
assert(css.includes('.vc-review-gate:not([hidden])'),'review gate must remain visible on iPad');
assert(html.includes('id="vcReviewGate"') && html.includes('id="vcLearningInsights"'),'current production review and history features retained');
assert(html.includes('id="vcReviewNextPassed"'),'current full sentence reading gate retained');
assert(js.includes('nextTarget(session.answers,session.estimate)'),'adaptive engine untouched');
assert(originalCss.includes('v8.7.4'),'production base stylesheet retained');
console.log('PASS iPad release: responsive tablet patch + review gate + existing production features');
