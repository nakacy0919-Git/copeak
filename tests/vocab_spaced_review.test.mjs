import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const js=fs.readFileSync(new URL('../vocabulary-review.js',import.meta.url),'utf8');
const ctx={};vm.runInNewContext(js,ctx);
const mod=ctx.CopeakVocabularyReview;
const t=Date.parse('2026-11-03T03:00:00.000Z'),day=86400000;
const hist=[{at:new Date(t-3*day).toISOString(),answers:[{id:'CK2-001',correct:false,level:2}]}];
let ledger=mod.reconcile(mod.initial(),hist,t);
assert.deepEqual(mod.dueItems(ledger,t).map(x=>x.id),['CK2-001']);
ledger=mod.applyReading(ledger,'CK2-001',79,t);
assert.equal(mod.dueItems(ledger,t).length,1);
ledger=mod.applyReading(ledger,'CK2-001',85,t);
assert.equal(mod.dueItems(ledger,t).length,0);
assert.equal(mod.dueItems(ledger,t+day+1).length,1);
ledger=mod.applyReading(ledger,'CK2-001',92,t+day+1);
assert.equal(mod.dueItems(ledger,t+3*day).length,0);
assert.equal(mod.dueItems(ledger,t+4*day+2).length,1);
const newMiss=[{at:new Date(t+5*day).toISOString(),answers:[{id:'CK2-001',correct:false,level:2}]}];
ledger=mod.reconcile(ledger,newMiss,t+5*day);
assert.equal(mod.dueItems(ledger,t+5*day).length,1);
assert.equal(mod.metrics(ledger,t+5*day).lapsed,1);
ledger=mod.reconcile(ledger,newMiss,t+5*day);
assert.equal(ledger.items['CK2-001'].mistakes,2,'diagnosis must not double-count on refresh');
const legacy=mod.normalize({completed:['CK2-001'],skippedAt:hist[0].at},hist,t);
assert.equal(mod.dueItems(legacy,t).length,1,'old completed words reenter review conservatively');
assert.equal(mod.metrics(ledger).laterCorrect,0);
const correct=[{at:new Date(t+6*day).toISOString(),answers:[{id:'CK2-001',correct:true,level:2}]}];
ledger=mod.reconcile(ledger,correct,t+6*day);
assert.equal(mod.metrics(ledger).laterCorrect,1,'correct later diagnosis is separate from reading pass');
console.log('PASS spaced review: intervals, reactivation, idempotence, migration and later-check evidence.');
