import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const h=fs.readFileSync('vocabulary-check.html','utf8'),js=fs.readFileSync('vocabulary-check.js','utf8'),css=fs.readFileSync('vocabulary-reading-focus.css','utf8');
new vm.Script(js);
const ids=[...h.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);assert.equal(ids.length,new Set(ids).size);
assert(h.includes('vocabulary-reading-focus.css?v=8.8.0'));
assert(h.indexOf('vocabulary-reading-focus.css')>h.indexOf('vocabulary-ipad.css'));
assert(!h.includes('id="vcResultMode"'));
const card=h.split('class="vc-reading-sentence-card"')[1].split('class="vc-reading-area"')[0];
assert(card.includes('id="vcReviewSentenceButton"')&&card.includes('id="vcReviewSentenceJa"'));
assert(h.includes('id="vcReviewBack"'));
assert(js.includes("classList.toggle('vc-review-focus',next==='review')"));
assert(js.includes("classList.remove('vc-review-focus')"));
assert(js.includes("$('vcReviewBack').addEventListener('click',()=>setResultTab('summary'))"));
assert(css.includes('.vc-result-tabs')&&css.includes('display:none!important'));
assert(css.includes('vc-reading-sentence-card')&&css.includes('.vc-transcript-words'));
assert(js.includes('recordReviewCompletion(item,percent)'));
console.log('PASS v8.8.0: focused review layout, localized back navigation, full-sentence reading preserved');