import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('vocabulary-check.html'),js=read('vocabulary-check.js'),css=read('vocabulary-check.css');
const bank=JSON.parse(read('data/v8-diagnostic-800.json')).questions;
const gloss=JSON.parse(read('data/v8-2-example-ja.json')).items;
const q=bank.find(q=>q.id==='CK7-153');
assert.equal(q.example_en,'Officials should avoid a conflict of interest when making decisions about public contracts.');
const entry=gloss.find(x=>x.id==='CK7-153');
assert.equal(entry.source_example_en,q.example_en);
assert(entry.example_ja.includes(entry.focus_ja));
assert(gloss.every(x=>x.example_ja.includes(x.focus_ja)));
assert(html.includes('id="vcReadingFeedback">')&&!html.includes('id="vcReadingFeedback" hidden'));
assert(html.indexOf('id="vcReadTranscript"')<html.indexOf('id="vcReadPercent"'));
assert(html.includes('class="vc-gauge-percent"')&&html.includes('data-t="readingAccuracy">Accuracy'));
assert(js.includes('resetReadingFeedback();')&&js.includes('renderReviewJapanese(item);'));
assert(js.includes("readingAccuracy:'Accuracy'"));
assert(js.includes('translationPending:'));
assert(css.includes('grid-template-columns:minmax(0,1fr) 150px'));
console.log('PASS v8.4 review: enriched English, linked Japanese underlines, always-visible transcript, right gauge, readable %.');
